"""资源加载器的结构化消费接口。"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Dict, List, Optional, Protocol, Set

from nova_harness.extensions.protocol import EventBusProtocol

if TYPE_CHECKING:
    from nova_harness.extensions.loading import LoadedExtensionsResult
    from nova_harness.resources.context_files import ContextFile
    from nova_harness.resources.extension_paths import ResourceExtensionPaths
    from nova_harness.resources.skills import Skill


class ResourceLoaderProtocol(Protocol):
    """资源加载能力，覆盖 prompts / extensions / agents / skills / tools 等。"""

    @property
    def event_bus(self) -> EventBusProtocol: ...

    async def reload(
        self, pre_trust_extensions: Optional[LoadedExtensionsResult] = None
    ) -> None: ...

    def extend_resources(self, paths: ResourceExtensionPaths) -> None: ...
    def get_prompts(self) -> Dict[str, Any]: ...
    def get_extensions(self) -> LoadedExtensionsResult: ...
    def get_disabled_extension_names(self) -> Set[str]: ...
    def get_agents(self) -> Dict[str, Any]: ...
    def get_agent_names(self) -> List[str]: ...
    def get_skills(self) -> Dict[str, Any]: ...
    def get_personas(self) -> Dict[str, Any]: ...
    def get_tools(self) -> Dict[str, Any]: ...
    def get_context_files(self) -> List[ContextFile]: ...


__all__ = ["ResourceLoaderProtocol"]

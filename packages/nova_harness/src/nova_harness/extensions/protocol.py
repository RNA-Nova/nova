"""扩展事件总线、API 工厂与运行器接口。"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Callable, Dict, List, Literal, Optional, Protocol

if TYPE_CHECKING:
    from nova_harness.extensions.extension import Extension
    from nova_harness.extensions.runtime import ExtensionRuntime
    from nova_harness.ui import UIContext


class EventBusProtocol(Protocol):
    """扩展间异步/同步事件分发能力。"""

    def emit(self, event_type: str, payload: Any) -> None: ...


ExtensionAPIFactory = Callable[["Extension", "ExtensionRuntime"], Any]
"""根据扩展对象与运行时构造扩展 API 实例。"""


class ExtensionRunnerProtocol(Protocol):
    """控制器与 ``AgentSession`` 使用的扩展运行器能力子集。"""

    project_trusted: Optional[bool]
    runtime: ExtensionRuntime
    ui_context: Optional[UIContext]
    extensions: List[Any]

    def get_command(self, name: str) -> Optional[Any]: ...
    def get_registered_commands(self) -> List[Any]: ...
    def create_command_context(self, extension: Optional[Any] = None) -> Any: ...
    def has_handlers(self, event_type: str) -> bool: ...

    # 事件负载为开放集（扩展可注册自定义事件类型）。
    async def emit(self, event: Any) -> Any: ...
    async def emit_model_select(self, event: Any) -> Any: ...
    async def emit_thinking_level_select(self, event: Any) -> Any: ...
    async def emit_message_end(self, event: Any) -> Any: ...
    async def emit_tool_call(self, event: Any) -> Any: ...
    async def emit_tool_result(self, event: Any) -> Any: ...
    async def emit_user_bash(self, event: Any) -> Any: ...
    async def emit_prepare_next_turn(self, event: Any) -> Any: ...
    async def emit_should_stop_after_turn(self, event: Any) -> Any: ...
    async def emit_context(
        self, messages: List[Any], signal: Optional[Any] = None
    ) -> List[Any]: ...
    async def emit_input(self, event: Any) -> Any: ...
    async def emit_before_agent_start(self, event: Any) -> Any: ...
    async def emit_before_provider_headers(self, headers: Any) -> Any: ...
    async def emit_before_provider_request(self, payload: Any) -> Any: ...
    async def emit_resources_discover(
        self, cwd: str, reason: Literal["startup", "reload"] = "startup"
    ) -> Any: ...

    def on_error(self, listener: Callable[[Any], None]) -> Callable[[], None]: ...
    def emit_error(self, error: Any) -> None: ...
    def invalidate(self, message: Optional[str] = None) -> None: ...
    def get_flag_values(self) -> Dict[str, Any]: ...
    def set_ui_context(self, ui_context: Optional[Any] = None) -> None: ...
    def bind_command_context(self, actions: Optional[Any] = None) -> None: ...
    def bind_core(
        self,
        actions: Any,
        context_actions: Any,
        provider_actions: Optional[Any] = None,
    ) -> None: ...


__all__ = ["EventBusProtocol", "ExtensionAPIFactory", "ExtensionRunnerProtocol"]

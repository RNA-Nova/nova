/** 吉祥物宽度（终端列数 = 像素列数）。 */
export const BLOB_WIDTH = 24;

/** 逐行渲染为 24-bit 真彩字符串行（▀ 半块一格两像素）。 */
export function blobMascotLines(): string[] {
  const lines: string[] = [];
  for (const row of BLOB_PIXELS) {
    let out = '';
    let i = 0;
    while (i < row.length) {
      const cell = row[i];
      const fg = cell?.[0] ?? null;
      const bg = cell?.[1] ?? null;
      // 同色对连跑（减少 ANSI 段数）
      let j = i + 1;
      while (j < row.length) {
        const next = row[j];
        if ((next?.[0] ?? null) === fg && (next?.[1] ?? null) === bg) j++;
        else break;
      }
      const n = j - i;
      if (fg === null && bg === null) {
        out += ' '.repeat(n);
      } else if (fg !== null && bg !== null) {
        out += chalk.hex(fg).bgHex(bg)('▀'.repeat(n));
      } else if (fg !== null) {
        out += chalk.hex(fg)('▀'.repeat(n));
      } else if (bg !== null) {
        out += chalk.hex(bg as string)('▄'.repeat(n));
      }
      i = j;
    }
    lines.push(out);
  }
  return lines;
}

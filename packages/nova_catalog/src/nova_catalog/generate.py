#!/usr/bin/env python3
"""模型目录种子生成器（对位 pi ``catalog/generate.ts``）。

构建归 ``nova_catalog.build.build_catalog``；本脚本只负责产物序列化与事务
提交。默认写入 monorepo 中的 nova_ai；内部调用方可显式传入其他包根，无需
环境变量或模块级可变路径。
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import shutil
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from nova_catalog import model_data as mdata
from nova_catalog.build import build_catalog
from nova_catalog.define import ProviderDefinition
from nova_catalog.providers import PROVIDERS
from nova_catalog.sources.models_dev import ModelsDevSource
from nova_protocol import ModelFields

_SHARD_TEMPLATE = '''\
# This file is auto-generated by catalog/generate.py
# Do not edit manually - run 'pixi run -e dev generate-models' to update

"""{label} 模型目录（生成 shard）。"""

import json
from importlib.resources import files
from typing import Dict

from nova_protocol import Model

from nova_ai.model_catalog import flatten_model_catalog

{prefix}_MODELS: Dict[str, Model] = flatten_model_catalog(
    "{provider_id}",
    json.loads(
        (files("nova_ai.providers") / "data" / "{provider_id}.json").read_text("utf-8")
    ),
)


def get_{module}_model(model_id: str) -> Model:
    """通过 ID 获取 {label} 模型。"""
    if model_id not in {prefix}_MODELS:
        raise KeyError(f"{label} model not found: {{model_id}}")
    return {prefix}_MODELS[model_id]


def list_{module}_models() -> Dict[str, Model]:
    """列出所有 {label} 模型。"""
    return {prefix}_MODELS.copy()
'''

_AGGREGATOR_TEMPLATE = '''\
# This file is auto-generated by catalog/generate.py
# Do not edit manually - run 'pixi run -e dev generate-models' to update

"""生成的模型目录聚合器（对齐 TS ``src/models.generated.ts``）。"""

{imports}

PROVIDER_IDS = {provider_ids}

GENERATED_PROVIDER_MODELS = {{
{entries}
}}
'''


def _commit_staged(
    stage_root: Path,
    targets: Dict[Path, str],
    data_only: bool,
    *,
    package_root: Path,
) -> None:
    """暂存校验 → 提交 → 正式树复验；任何失败都完整回滚。"""
    data_dir = mdata.generated_data_dir(package_root)
    providers_dir = mdata.generated_providers_dir(package_root)
    aggregator = mdata.generated_aggregator_path(package_root)
    deletions: List[Path] = []
    # JSON 清理由本次数据目标集决定，data-only 也应能删掉多余文件。
    for path in data_dir.glob("*.json"):
        if path.name != mdata.MODEL_DATA_MANIFEST_FILE and path not in targets:
            deletions.append(path)
    if not data_only:
        # shard 清理由本次代码目标集决定，完全不依赖旧聚合器是否可解析。
        for shard in providers_dir.glob("*/models.py"):
            if shard not in targets:
                deletions.append(shard)

    # 暂存树需要一套完整四方对账：聚合器、现有 shard、数据与 manifest。
    if aggregator.exists():
        staged_aggregator = stage_root / aggregator.relative_to(package_root)
        staged_aggregator.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(aggregator, staged_aggregator)
    if data_dir.exists():
        shutil.copytree(data_dir, stage_root / data_dir.relative_to(package_root))
    for shard in providers_dir.glob("*/models.py"):
        staged = stage_root / shard.relative_to(package_root)
        staged.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(shard, staged)
    for target, content in targets.items():
        staged = stage_root / target.relative_to(package_root)
        staged.parent.mkdir(parents=True, exist_ok=True)
        staged.write_text(content, "utf-8")
    for target in deletions:
        (stage_root / target.relative_to(package_root)).unlink(missing_ok=True)
    mdata.validate_generated_model_data(stage_root)

    selected = (
        {path: content for path, content in targets.items() if data_dir in path.parents}
        if data_only
        else targets
    )
    affected = [*selected, *deletions]
    previous = {
        target: target.read_bytes() if target.exists() else None for target in affected
    }
    try:
        for target in selected:
            target.parent.mkdir(parents=True, exist_ok=True)
            os.replace(stage_root / target.relative_to(package_root), target)
        for target in deletions:
            target.unlink(missing_ok=True)
        mdata.validate_generated_model_data(package_root)
    except Exception:
        for target in reversed(affected):
            old = previous[target]
            if old is None:
                target.unlink(missing_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(old)
        raise


def _model_api(fields: ModelFields) -> str:
    api = fields.get("api")
    if not isinstance(api, str) or not api:
        raise ValueError("generated model is missing api")
    # Api 是开放字符串集合；是否可执行由 provider 的 API 实现路由决定。
    return api


def _group_by_api(models: Dict[str, ModelFields]) -> Dict[str, Dict[str, Any]]:
    """按每个模型的 api 分片；同 provider 混合协议不会挤进第一组。"""
    groups: Dict[str, Dict[str, Any]] = {}
    for model_id, fields in sorted(models.items()):
        groups.setdefault(_model_api(fields), {})[model_id] = fields
    return groups


def _models_by_id(models: List[ModelFields]) -> Dict[str, ModelFields]:
    result: Dict[str, ModelFields] = {}
    for model in models:
        model_id = model.get("id")
        if not isinstance(model_id, str) or not model_id:
            raise ValueError("generated model is missing id")
        if model_id in result:
            raise ValueError(f"duplicate generated model id: {model_id}")
        result[model_id] = model
    return result


def main(
    argv: Optional[Sequence[str]] = None,
    *,
    package_root: Optional[Path] = None,
    provider_definitions: Optional[Sequence[ProviderDefinition]] = None,
    source: Optional[ModelsDevSource] = None,
) -> int:
    parser = argparse.ArgumentParser(description="生成 nova_ai 模型目录种子")
    parser.add_argument("--strict", action="store_true", help="数据源异常即抛")
    parser.add_argument(
        "--data-only", action="store_true", help="只提交数据分片与 manifest"
    )
    parser.add_argument("--pretty", action="store_true", help="数据分片缩进输出")
    args = parser.parse_args(argv)

    package_root = package_root or mdata.default_package_root()
    providers = sorted(
        (PROVIDERS if provider_definitions is None else list(provider_definitions)),
        key=lambda provider: provider.id,
    )
    if args.data_only:
        # 只更新现有聚合器覆盖的 provider；新增 provider 不偷渡。
        provider_ids = set(mdata.read_provider_ids(package_root))
        available = {provider.id for provider in providers}
        missing = sorted(provider_ids - available)
        if missing:
            raise ValueError(
                "data-only cannot preserve providers missing from catalog "
                f"definitions: {', '.join(missing)}; run a full generation"
            )
        providers = [provider for provider in providers if provider.id in provider_ids]

    print("Fetching models from models.dev API...")
    built = asyncio.run(
        build_catalog(
            providers,
            source or ModelsDevSource(),
            strict=args.strict,
        )
    )
    # 与 pi 一致：没有模型的 provider 不进入任何生成产物。
    built = {pid: models for pid, models in built.items() if models}
    for provider_id, models in sorted(built.items()):
        print(f"{provider_id}: {len(models)} models")

    indent = 2 if args.pretty else None
    targets: Dict[Path, str] = {}
    data_files: Dict[str, str] = {}
    data_dir = mdata.generated_data_dir(package_root)
    for provider in providers:
        models = built.get(provider.id)
        if not models:
            continue
        by_id = _models_by_id(models)
        groups = _group_by_api(by_id)
        content = (
            json.dumps(
                groups,
                ensure_ascii=False,
                indent=indent,
                sort_keys=True,
                allow_nan=False,
            )
            + "\n"
        )
        filename = f"{provider.id}.json"
        targets[data_dir / filename] = content
        data_files[filename] = content
        targets[mdata.generated_shard_path(package_root, provider.id)] = (
            _SHARD_TEMPLATE.format(
                label=provider.name,
                prefix=provider.id.upper().replace("-", "_"),
                provider_id=provider.id,
                module=provider.id.replace("-", "_"),
            )
        )

    structure = {
        pid: {mid: _model_api(fields) for mid, fields in _models_by_id(models).items()}
        for pid, models in built.items()
    }
    manifest = mdata.create_model_data_manifest(
        structure,
        data_files,
        datetime.now(timezone.utc).isoformat(timespec="seconds"),
    )
    targets[data_dir / mdata.MODEL_DATA_MANIFEST_FILE] = (
        json.dumps(
            manifest, ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False
        )
        + "\n"
    )

    imports = "\n".join(
        f"from nova_ai.providers.{p.id.replace('-', '_')}.models "
        f"import {p.id.upper().replace('-', '_')}_MODELS"
        for p in providers
        if built.get(p.id)
    )
    entries = ",\n".join(
        f'    "{p.id}": {p.id.upper().replace("-", "_")}_MODELS'
        for p in providers
        if built.get(p.id)
    )
    targets[mdata.generated_aggregator_path(package_root)] = (
        _AGGREGATOR_TEMPLATE.format(
            imports=imports,
            provider_ids=repr(sorted(built)),
            entries=entries,
        )
    )

    package_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".catalog-stage-", dir=package_root) as tmp:
        _commit_staged(Path(tmp), targets, args.data_only, package_root=package_root)
    print(
        f"Generated and validated {len(data_files)} data shards"
        + (" (data-only)" if args.data_only else " + code shards")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""模型目录种子生成器（对位 pi ``catalog/generate.ts``——管线唯一入口）。

自包含管线（``catalog/``——pi 同款：构建期世界独立成区）：知识归
``providers/`` 各家定义，族事实归 ``families/``，薄拉取归 ``sources/``，
引擎归 ``build.py``。本脚本只负责**发射构建期种子**：数据分片
（``providers/data/<id>.json``）、生成 shard（``providers/<module>/models.py``）、
聚合器（``models_generated.py``）与 manifest（schemaVersion +
generatedAt + 结构/文件哈希）。

种子是冷启动/离线兜底与测试 fixture；运行时的新鲜数据由 harness 组合根
装配的刷新策略物化到 ``~/.nova/agent/models-store.json``。

用法::

    pixi run -e dev generate-models                 # 重新生成种子
    pixi run -e dev generate-models --data-only     # 只重写数据分片与 manifest
    pixi run -e dev generate-models --strict        # 数据源异常即抛
    pixi run -e dev check-model-data                # 保鲜检查（漂移即红）
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict

# 产物目标：nova_ai 包根（默认 monorepo 兄弟目录约定，NOVA_AI_PACKAGE_ROOT 可覆盖）
NOVA_AI_ROOT = Path(
    os.environ.get("NOVA_AI_PACKAGE_ROOT")
    or str(Path(__file__).resolve().parents[2] / "nova_ai")
)

from nova_catalog import model_data as mdata  # noqa: E402
from nova_catalog.build import build_one, prepare_sources  # noqa: E402
from nova_catalog.context import BuildContext  # noqa: E402
from nova_catalog.providers import PROVIDERS  # noqa: E402
from nova_catalog.sources.ark import fetch_ark_status  # noqa: E402
from nova_catalog.sources.models_dev import ModelsDevSource  # noqa: E402

_SHARD_TEMPLATE = '''\
# This file is auto-generated by catalog/generate.py
# Do not edit manually - run 'pixi run -e dev generate-models' to update

"""{label} 模型目录（生成 shard）。"""

import json
from importlib.resources import files
from typing import Dict

from nova_protocol import Model

from nova_ai.model_catalog import flatten_model_catalog

{prefix}_MODELS: Dict[str, Model] = flatten_model_catalog(
    "{provider_id}",
    json.loads(
        (files("nova_ai.providers") / "data" / "{provider_id}.json").read_text("utf-8")
    ),
)


def get_{module}_model(model_id: str) -> Model:
    """通过 ID 获取 {label} 模型。"""
    if model_id not in {prefix}_MODELS:
        raise KeyError(f"{label} model not found: {{model_id}}")
    return {prefix}_MODELS[model_id]


def list_{module}_models() -> Dict[str, Model]:
    """列出所有 {label} 模型。"""
    return {prefix}_MODELS.copy()
'''

_AGGREGATOR_TEMPLATE = '''\
# This file is auto-generated by catalog/generate.py
# Do not edit manually - run 'pixi run -e dev generate-models' to update

"""生成的模型目录聚合器（对齐 TS ``src/models.generated.ts``）。"""

{imports}

PROVIDER_IDS = {provider_ids}

GENERATED_PROVIDER_MODELS = {{
{entries}
}}
'''


def _write_if_changed(path: Path, content: str) -> bool:
    old = path.read_text("utf-8") if path.exists() else None
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, "utf-8")
    return old != content


async def _fetch_and_build(
    providers: Any, strict: bool
) -> "tuple[Dict[str, Dict[str, Dict[str, Any]]], Any]":
    """models.dev 裸数据 → 翻译+修正组装（HTTP 全异步段）。

    知识全归 ``catalog/providers/`` 各家定义；``BuildContext`` 持有源捆、
    ark 状态与派生执行点；``prepare_sources`` 预拉全部直取家切片后，
    逐家过 ``build_one``（主流水线 + finalize/finalize_all 逃生口）。
    """
    source = ModelsDevSource()
    ark_status = await fetch_ark_status(os.environ.get("VOLCENGINE_API_KEY"))

    ctx = BuildContext(
        {p.id: p for p in providers}, source, strict=strict, ark_status=ark_status
    )
    ctx.register_build_fn(lambda p: build_one(p, ctx))
    await prepare_sources(list(providers), ctx)

    built: Dict[str, Dict[str, Dict[str, Any]]] = {}
    for provider in providers:
        models = build_one(provider, ctx)
        ctx.register_built(provider.id, models)
        built[provider.id] = {str(m["id"]): m for m in models}
        dropped = len(ctx.raw_for(provider)) - len(models)
        print(
            f"{provider.id}: {len(models)} models"
            + (
                f"（源 {len(ctx.raw_for(provider))}，过滤/钉住净变动 {dropped}）"
                if dropped
                else ""
            )
        )
    return built, ark_status


def main(argv: Any = None) -> int:
    parser = argparse.ArgumentParser(description="生成 nova_ai 模型目录种子")
    parser.add_argument(
        "--strict", action="store_true", help="数据源异常时抛错（build 用）"
    )
    parser.add_argument(
        "--data-only", action="store_true", help="只重写数据分片与 manifest"
    )
    parser.add_argument("--pretty", action="store_true", help="数据分片缩进输出")
    args = parser.parse_args(argv)

    print("Fetching models from models.dev API...")
    # 知识归 catalog/providers 注册表；按 id 排序保证生成物字节稳定
    providers = sorted(PROVIDERS, key=lambda p: p.id)

    # HTTP 已全异步化——拉取与组装段包一层 asyncio.run
    built, ark_status = asyncio.run(_fetch_and_build(providers, args.strict))
    if ark_status:
        print(f"Ark liveness: {len(ark_status)} retired/retiring models")
    else:
        print("Ark liveness skipped (no VOLCENGINE_API_KEY)")

    # ---- 写数据分片 ----
    data_dir = NOVA_AI_ROOT / "src" / "nova_ai" / "providers" / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    indent = 2 if args.pretty else None
    file_contents: Dict[str, str] = {}
    for provider in providers:
        provider_built = built[provider.id]
        # api 组键取建成品的协议戳（源数据驱动——各目录 api 单一，取任一）
        api = next(iter(provider_built.values()))["api"]
        groups = {api: dict(sorted(provider_built.items()))}
        content = json.dumps(groups, ensure_ascii=False, indent=indent, sort_keys=True)
        filename = f"{provider.id}.json"
        (data_dir / filename).write_text(content + "\n", "utf-8")
        file_contents[filename] = content + "\n"

    # ---- manifest ----
    structure = {
        pid: {mid: fields["api"] for mid, fields in models.items()}
        for pid, models in built.items()
    }
    manifest = mdata.create_model_data_manifest(
        structure,
        file_contents,
        datetime.now(timezone.utc).isoformat(timespec="seconds"),
    )
    (data_dir / mdata.MODEL_DATA_MANIFEST_FILE).write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        "utf-8",
    )
    print(f"wrote {len(file_contents)} data shards + manifest")

    if args.data_only:
        print("data-only: shards/aggregator untouched")
        return 0

    # ---- 生成 shard 与聚合器 ----
    rewritten = 0
    for provider in providers:
        module_name = provider.id.replace("-", "_")
        shard = _SHARD_TEMPLATE.format(
            label=provider.name,
            prefix=provider.id.upper().replace("-", "_"),
            provider_id=provider.id,
            module=module_name,
        )
        shard_path = (
            NOVA_AI_ROOT / "src" / "nova_ai" / "providers" / module_name / "models.py"
        )
        if _write_if_changed(shard_path, shard):
            rewritten += 1

    imports = "\n".join(
        f"from nova_ai.providers.{p.id.replace('-', '_')}.models "
        f"import {p.id.upper().replace('-', '_')}_MODELS"
        for p in providers
    )
    entries = ",\n".join(
        f'    "{p.id}": {p.id.upper().replace("-", "_")}_MODELS' for p in providers
    )
    aggregator = _AGGREGATOR_TEMPLATE.format(
        imports=imports,
        provider_ids=repr(sorted(p.id for p in providers)),
        entries=entries,
    )
    if _write_if_changed(
        NOVA_AI_ROOT / "src" / "nova_ai" / "models_generated.py", aggregator
    ):
        rewritten += 1
    print(f"rewrote {rewritten} generated files")

    # ---- 自校验：生成即验收 ----
    mdata.validate_generated_model_data(NOVA_AI_ROOT)
    print("Generated model data is valid.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
